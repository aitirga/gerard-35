// Generated by `just character`; ?character=<file name> previews another one in development.
const CHARACTERS = import.meta.glob<CharacterSpec>('./characters/*.json', { eager: true, import: 'default' });
function playerCharacter(adult = false) {
  const requested = import.meta.env.DEV ? new URLSearchParams(location.search).get('character') : null;
  return CHARACTERS[`./characters/${requested}.json`] ?? CHARACTERS[adult ? './characters/gerard-adult.json' : './characters/gerard-child.json'];
}
/** Gerard at 35 is drawn taller than the boy (provisional model, docs/lore.md). */
const ADULT_SCALE = 1.26;

export interface GameCallbacks {
  onEncounter: (allies: 1 | 2, foes: number, options: { possessed: boolean; encounter: Encounter }) => void;
  /** A fight closed, however it ended. */
  onBattleEnd: (phase: BattlePhase, encounter: Encounter) => void;
  onBattleTargets: (targets: { id: string; x: number; y: number; visible: boolean }[]) => void;
  /** Where the companion's head is on screen, for speech bubbles; undefined when he is not shown. */
  onCompanionScreen: (at: { x: number; y: number } | undefined) => void;
  onStep: (steps: number, cell: Cell) => void;
  onLocation: (id: EnvironmentId, cell: Cell) => void;
  onInteraction: (interaction: Interaction | undefined) => void;
  onDialogue: (dialogue: Dialogue) => void;
  /** Something the story should react to: a story interaction, the south of the street, the leash. */
  onStory: (event: StoryEvent) => void;
}
/** Parts of Gerard's model that only show once he picks up his backpack. */
const BACKPACK_PARTS = new Set(['Mochila', 'Bolsillo de mochila', 'Correa frontal', 'Correa de hombro', 'Hebilla de mochila']);
const SANT_QUIRZE = new Set<EnvironmentId>(['maresme', 'home-entrance', 'home-floor-1', 'home-floor-2']);
/** Where Bernat walks with Gerard: Sant Quirze, and La Reina Bubbaloo's palace at the end of it. */
const WITH_BERNAT = new Set<EnvironmentId>([...SANT_QUIRZE, 'palacio']);
/** Where the palace fight is staged: the middle of the wrapper room. */
const PALACE_STAGE: Cell = { x: 5, z: 15.5 };
const PICKUP_COLOURS: Record<ItemId, [string, string]> = { pocion: ['#a77ad6', '#f0d36b'], mochila: ['#527e6e', '#355b50'], zapatillas: ['#dfd9bd', '#e9ad48'], chicle: ['#ff6fae', '#fbeef3'], envoltorio: ['#ff6fae', '#fbeef3'] };

export function createGame(canvas: HTMLCanvasElement, callbacks: GameCallbacks, story: Story) {
  const app = new pc.Application(canvas, { graphicsDeviceOptions: { antialias: true, alpha: false } });
  app.graphicsDevice.maxPixelRatio = Math.min(window.devicePixelRatio, 2);
  app.setCanvasFillMode(pc.FILLMODE_FILL_WINDOW);
  app.setCanvasResolution(pc.RESOLUTION_AUTO);
  let environment = ENVIRONMENTS[story.resume.environment];
  const movement = new FreeMovement(environment.grid, story.resume.cell);
  let scenery = buildScenery(app, environment);
  const camera = new pc.Entity('Cámara isométrica');
  camera.addComponent('camera', {
    projection: pc.PROJECTION_ORTHOGRAPHIC, orthoHeight: 11,
    clearColor: new pc.Color(0.2, 0.26, 0.24), nearClip: 0.1, farClip: 180, toneMapping: pc.TONEMAP_ACES,
  });
  app.root.addChild(camera);
  const player = new pc.Entity('Jugador');
  app.root.addChild(player);
  // Gerard's model: the boy in chapter 1, the man at 35 once he wakes up (`dress`).
  let rig = buildCharacter(playerCharacter(), player), grownUp = false;
  player.setPosition(0, 0.06, 0);
  let plantFeet = createGroundContact(player, rig.feet);
  const effects = createEffects(app);
  const battleScene = createBattleScene(app, player, (x, z) => scenery.groundHeight(x, z), effects);
  const pack = new WanderingPack(ENVIRONMENTS.maresme.grid, Math.random, STREET_END_AREA);
  let battle: BattleState | undefined;
  let paused = false;
  // La Reina Bubbaloo's minion: hidden in the manhole; its entrance holds the street still.
  const minion = createMinion(app, effects);
  let cutscene = false;
  let possessed = false;
  /** 0 is the scene's own light, 1 is La Reina Bubbaloo's; `toneTarget` fades in over a few seconds. */
  let tone = 0, toneTarget = 0;
  /** Seconds until a possessed dog gives off its next mote. */
  let spores = 0, sporeDog = 0;
  const dayClear = new pc.Color(0.2, 0.26, 0.24), clear = new pc.Color();
  const stopped = () => paused || cutscene;
  // La Reina Bubbaloo's palace past the north end of the street, and the street's own changes.
  const palace = createPalace(app, effects);
  let approach: PalaceApproach | undefined;
  /** A cut-scene camera: what to look at and how much to frame, instead of following Gerard. */
  let cinematic: { target: pc.Vec3; height: number } | undefined;
  const cameraWobble = new pc.Vec3();
  /** The palace minion has climbed out of its drain (not saved: on reload it waits below again). */
  let drainRisen = false;
  let encounterId: Encounter = 'dogs';
  let room: string | undefined;
  let away = false;
  battleScene.setMinionTemplate(minion.root);
  const reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');
  let backpack = rig.body.find(node => BACKPACK_PARTS.has(node.name)) as pc.Entity[];
  function dress(adult: boolean) {
    if (adult === grownUp) return;
    grownUp = adult;
    rig.body.destroy(); rig.materials.forEach(m => m.destroy());
    rig = buildCharacter(playerCharacter(adult), player);
    const s = adult ? ADULT_SCALE : 1; player.setLocalScale(s, s, s);
    plantFeet = createGroundContact(player, rig.feet);
    backpack = rig.body.find(node => BACKPACK_PARTS.has(node.name)) as pc.Entity[];
  }

  // Story cast: people standing in the house, loose items, and Bernat walking behind Gerard.
  const castRoot = new pc.Entity('Reparto');
  app.root.addChild(castRoot);
  let npcs: { entity: pc.Entity; cell: Cell; body: pc.Entity; materials: pc.Material[] }[] = [];
  let pickups: { entity: pc.Entity; cell: Cell; materials: pc.Material[]; spot?: { x: number; z: number; y: number } }[] = [];
  const companion = new pc.Entity('Bernat');
  app.root.addChild(companion);
  const bernatRig = buildCharacter(CHARACTERS['./characters/bernat-child.json'], companion);
  const bernatWalk = new WalkAnimation();
  const plantBernat = createGroundContact(companion, bernatRig.feet);
  const follower = new Follower(PLACES.bernat.cell);
  let companionShown = false;
  let tug = 0;
  /** Bernat walks with Gerard around Sant Quirze, not into other chapters' scenes. */
  function bernatHere() { return story.companion !== 'none' && WITH_BERNAT.has(environment.id); }
  /** While Bernat stalls, cells just beyond the leash are walls, so Gerard cannot leave him. */
  function leashCells(): Cell[] {
    if (story.companion !== 'stalled') return [];
    const b = follower.position, cells: Cell[] = [];
    for (let z = Math.floor(b.z - LEASH - 3); z <= b.z + LEASH + 3; z++) for (let x = Math.floor(b.x - LEASH - 3); x <= b.x + LEASH + 3; x++) {
      const d = Math.hypot(x - b.x, z - b.z);
      if (d > LEASH + 0.5 && d <= LEASH + 2.5) cells.push({ x, z });
    }
    return cells;
  }
  function occupiedCells(): readonly Cell[] {
    const drain = environment.id === 'palacio' && drainRisen && !story.has('wrapper-room') ? [{ x: PLACES.drain.x, z: PLACES.drain.z }] : [];
    return [...npcs.map(n => n.cell), ...story.blocked(environment.id), ...drain, ...(environment.id === 'maresme' ? [...pack.occupied, ...leashCells()] : [])];
  }
  function interactions(): Interaction[] {
    return [...environment.interactions, ...story.interactions(environment.id, bernatHere() ? follower.position : undefined)];
  }
  /** The closest thing within reach, so a pickup next to a door still gets picked. */
  function nearby(position: Cell): Interaction | undefined {
    const inReach = interactions().map(i => ({ i, d: Math.hypot(i.cell.x - position.x, i.cell.z - position.z) })).filter(({ d }) => d <= INTERACTION_REACH);
    // Bernat walks right behind Gerard: talking to him only wins when nothing else is in reach.
    const last = ({ i }: { i: Interaction }) => Number(i.id === 'talk-bernat');
    return inReach.sort((a, b) => last(a) - last(b) || a.d - b.d)[0]?.i;
  }
  function placeOnGround(entity: pc.Entity, cell: Cell, lift = 0) {
    const p = scenery.toWorld(cell.x, cell.z);
    entity.setPosition(p.x, scenery.groundHeight(p.x, p.z) + lift, p.z);
  }
  function pickupModel(id: ItemId, holder: pc.Entity) {
    const [main, trim] = PICKUP_COLOURS[id].map(hex => {
      const m = new pc.StandardMaterial(); m.diffuse.fromString(hex); m.emissive.fromString(hex); m.emissiveIntensity = .35; m.gloss = .6; m.update(); return m;
    });
    const part = (type: string, m: pc.Material, p: number[], sc: number[]) => {
      const e = new pc.Entity(); e.addComponent('render', { type, material: m, castShadows: true });
      e.setLocalPosition(p[0], p[1], p[2]); e.setLocalScale(sc[0], sc[1], sc[2]); holder.addChild(e);
    };
    if (id === 'envoltorio') {
      // A twisted Bubbaloo wrapper, flattened out: a pink-and-white middle and two twisted ends.
      part('box', main, [0, 0, 0], [.2, .05, .13]);
      part('box', trim, [0, .03, 0], [.12, .02, .135]);
      for (const side of [-1, 1]) part('cone', main, [side * .14, 0, 0], [.09, .1, .09]);
    } else if (id === 'pocion') {
      part('sphere', main, [0, 0, 0], [.26, .26, .26]);
      part('cylinder', main, [0, .17, 0], [.09, .12, .09]);
      part('cylinder', trim, [0, .26, 0], [.1, .06, .1]);
    } else {
      part('box', main, [0, 0, 0], [.34, .4, .2]);
      part('box', trim, [0, -.06, .11], [.24, .16, .06]);
      for (const side of [-1, 1]) part('box', trim, [side * .1, .02, -.11], [.05, .36, .03]);
    }
    return [main, trim];
  }
  /** Rebuilds the cast for the current scene from the story; call after any story change. */
  function refreshStory() {
    for (const list of [npcs, pickups]) for (const item of list) { item.entity.destroy(); item.materials.forEach(m => m.destroy()); }
    npcs = story.npcs(environment.id).map(npc => {
      const entity = new pc.Entity(npc.id); castRoot.addChild(entity);
      const rig = buildCharacter(CHARACTERS[`./characters/${npc.character}.json`], entity);
      entity.setLocalScale(npc.scale, npc.scale, npc.scale);
      placeOnGround(entity, npc.cell, .06);
      return { entity, cell: npc.cell, body: rig.body, materials: rig.materials };
    });
    pickups = story.pickups(environment.id).map(p => {
      const entity = new pc.Entity(`Objeto: ${p.id}`); castRoot.addChild(entity);
      placeOnGround(entity, p.cell, .75);
      return { entity, cell: p.cell, spot: p.spot, materials: pickupModel(p.id, entity) };
    });
    dress(story.adult);
    backpack.forEach(part => { part.enabled = story.has('got-backpack'); });
    if (!cutscene) {
      possessed = story.possessed;
      if (environment.id === 'palacio') minion.set(story.has('wrapper-room') ? 'gone' : drainRisen ? 'standing' : 'lurking');
      else minion.set(story.minion);
      if (environment.id === 'maresme') {
        if (story.palace && !approach) approach = buildApproach();
        palace.grow(story.palace ? 1 : 0); approach?.grow(story.palace ? 1 : 0);
      }
    }
    battleScene.possess(possessed);
    // The class look is the boy's outfit; at 35 he wakes in his pyjamas (the class stays in fights).
    if (story.gerardClass && !story.adult) wearClass(player, story.gerardClass);
    toneTarget = environment.id === 'palacio' || (SANT_QUIRZE.has(environment.id) && story.tone === 'bubbaloo') ? 1 : 0;
    // Bernat first steps out of his own front door; scene changes place him beside Gerard instead.
    if (bernatHere() && !companionShown) follower.reset(environment.id === 'maresme' ? PLACES.bernat.cell : beside(movement.cell));
    companionShown = bernatHere();
    companion.enabled = companionShown;
    movement.resolveOverlap(occupiedCells(), !reducedMotion.matches);
    lastPrompt = ''; updatePrompt();
  }
  /** A free cell next to `cell` for the companion to appear on after a scene change. */
  function beside(cell: Cell): Cell {
    const around = [{ x: 0, z: 1 }, { x: 1, z: 0 }, { x: -1, z: 0 }, { x: 0, z: -1 }].map(d => ({ x: cell.x + d.x, z: cell.z + d.z }));
    return around.find(c => environment.grid[c.z]?.[c.x] === '.' && !npcs.some(n => n.cell.x === c.x && n.cell.z === c.z)) ?? cell;
  }
  /** `forced` is the story's fight: it starts even though the pack has not wandered into Gerard. */
  function encounter(forced = false) {
    if (stopped() || battle || !story.battles || !pack.dogs.length || environment.id !== 'maresme' || document.querySelector('#hud[data-dialogue]')) return;
    if (!forced && !pack.ready) return;
    clearInput();
    movement.teleport(environment.grid, movement.cell);
    pack.armed = false;
    encounterId = 'dogs';
    callbacks.onEncounter(bernatHere() ? 2 : 1, pack.dogs.length, { possessed, encounter: 'dogs' });
  }
  /** The street dressing depends on this scene's houses, so it is rebuilt with the street. */
  function buildApproach() {
    const north = ['west-0', 'east-0', 'west-1', 'east-1'].map(id => scenery.houses.find(h => h.id === id)).filter(h => !!h);
    const { x, z } = PLACES.palace.door;
    return createPalaceApproach(app, north, { from: scenery.toWorld(x, 6.7), to: scenery.toWorld(x, z - .6) }, [scenery.toWorld(x - 3.4, 1.3), scenery.toWorld(x + 3.4, 1.3)]);
  }
  function placePalace() {
    const gate = scenery.toWorld(PLACES.palace.gate.x, PLACES.palace.gate.z);
    gate.y = scenery.groundHeight(gate.x, gate.z);
    palace.place(gate);
  }
  /** Waits for `seconds` of game time while `step(t)` runs each frame with t from 0 to 1. */
  let timeline: { seconds: number; elapsed: number; step: (t: number) => void; done: () => void } | undefined;
  function play(seconds: number, step: (t: number) => void) {
    return new Promise<void>(done => { timeline = { seconds, elapsed: 0, step, done }; });
  }
  function holdStill() { cutscene = true; clearInput(); movement.walking = false; callbacks.onInteraction(undefined); }
  function release() { cutscene = false; cinematic = undefined; lastPrompt = ''; updatePrompt(); }
  /**
   * The houses at the north end change and the palace inflates behind them
   * (docs/bubbaloo-palace.md): the camera pulls back to watch, then returns to Gerard.
   */
  async function raisePalace() {
    if (environment.id !== 'maresme') return;
    holdStill();
    approach ??= buildApproach();
    const gate = scenery.toWorld(PLACES.palace.gate.x, PLACES.palace.gate.z);
    cinematic = { target: gate.clone().add(new pc.Vec3(0, 3, 4)), height: 13.5 };
    await play(1.4, () => {});
    await play(7.5, t => {
      approach!.grow(Math.min(1, t * 1.6));
      palace.grow(Math.max(0, (t - .22) / .78));
      // A low rumble while the gum climbs the walls.
      if (t < .3 && !reducedMotion.matches) cameraWobble.set(Math.sin(t * 160) * .12, Math.sin(t * 130) * .06, 0); else cameraWobble.set(0, 0, 0);
    });
    effects.emit('spore', gate.clone().add(new pc.Vec3(0, 1.5, 1.5)), 26, 3);
    await play(1.2, () => {});
    release();
  }
  /** La Pompa bursts as they walk through; the story then moves them inside. */
  async function popGate() {
    holdStill();
    palace.popGate();
    await play(.5, () => {});
    release();
  }
  /** The palace minion climbs out of the drain in the wrapper room, and stays to fight. */
  async function riseFromDrain() {
    if (environment.id !== 'palacio') return;
    holdStill();
    const drain = scenery.toWorld(PLACES.drain.x, PLACES.drain.z);
    cinematic = { target: drain.clone().add(new pc.Vec3(0, 1, 0)), height: 5.5 };
    drainRisen = true;
    await minion.rise();
    await play(.6, () => {});
    release();
    movement.resolveOverlap(occupiedCells(), !reducedMotion.matches);
  }
  /**
   * The end of chapter 1 (docs/bubbaloo-palace.md): minions burst out of everywhere, and La
   * Reina Bubbaloo's gelatine hands come down from above the frame and close round both boys.
   * `fadeOut` darkens the screen while the hands hold them; then the crowd and hands go.
   */
  async function ambush(fadeOut: () => Promise<void>) {
    holdStill();
    const centre = player.getPosition().clone();
    if (bernatHere()) centre.lerp(centre, companion.getPosition(), .5);
    cinematic = { target: centre.clone().add(new pc.Vec3(0, .8, 0)), height: 6.8 };
    const ground = scenery.groundHeight(centre.x, centre.z);
    // Out of the floor all round them, wherever there is floor to come out of.
    const cell = movement.position, spots: Cell[] = [];
    for (let i = 0; i < 48 && spots.length < 12; i++) {
      const a = i * 2.39996, r = 2.2 + (i % 4) * .6;
      const c = { x: Math.round(cell.x + Math.sin(a) * r), z: Math.round(cell.z + Math.cos(a) * r) };
      if (environment.grid[c.z]?.[c.x] === '.' && !spots.some(o => o.x === c.x && o.z === c.z)) spots.push(c);
    }
    const crowd = spots.map((spot, i) => {
      const model = minion.root.clone(); model.enabled = true; app.root.addChild(model);
      const at = scenery.toWorld(spot.x, spot.z); at.y = ground;
      const size = .85 + (i % 4) * .12;
      model.setLocalScale(size, size, size);
      model.setEulerAngles(0, Math.atan2(centre.x - at.x, centre.z - at.z) * 180 / Math.PI, 0);
      return { model, at, delay: (i * 7 % 12) / 12 * .55, puffed: false };
    });
    const hands = createQueenHands(app); hands.aim(centre);
    // ¡BAM!: a jolt, then they rise out of the floor all round, gooey and fast.
    await play(2.4, t => {
      cameraWobble.set(t < .2 && !reducedMotion.matches ? Math.sin(t * 220) * .3 : 0, t < .2 ? Math.cos(t * 190) * .15 : 0, 0);
      for (const c of crowd) {
        const k = Math.min(1, Math.max(0, (t - c.delay) / .35));
        if (k > 0 && !c.puffed) { c.puffed = true; effects.emit('goo', c.at.clone().add(new pc.Vec3(0, .3, 0)), 6, .3); }
        const rise = k >= 1 ? 1 : 1 + 2.6 * (k - 1) ** 3 + 1.6 * (k - 1) ** 2;
        c.model.setPosition(c.at.x, c.at.y - 2.4 * (1 - rise), c.at.z);
      }
      hands.pose(0, 0);
    });
    // Her hands come down out of the sky: far too big for the frame.
    await play(2.4, t => {
      const k = t * t * (3 - 2 * t);
      hands.pose(k, 0); hands.update(1 / 60);
      cinematic!.height = 6.8 + k * 1.6;
      for (const c of crowd) c.model.setLocalEulerAngles(Math.sin(t * 20 + c.delay * 9) * 6, c.model.getLocalEulerAngles().y, 0);
    });
    await play(.8, t => {
      hands.pose(1, t * t * (3 - 2 * t));
      cameraWobble.set(t > .6 && !reducedMotion.matches ? Math.sin(t * 200) * .18 : 0, 0, 0);
    });
    cameraWobble.set(0, 0, 0);
    const fading = fadeOut();
    await play(1.2, t => hands.pose(1 - t * .08, 1));
    await fading;
    hands.destroy();
    crowd.forEach(c => c.model.destroy());
    cutscene = false; cinematic = undefined;
  }
  /** Gerard lying in bed; 1 = flat on his back, 0 = up on his feet beside it. */
  let lying: number | undefined;
  /** Chapter 2 opens: out of the black, Gerard bolts upright in bed and steps out of it. */
  async function wake(fadeIn: () => Promise<void>) {
    holdStill();
    lying = 1;
    const bed = scenery.toWorld(PLACES.bed.x, PLACES.bed.z);
    cinematic = { target: bed.clone().add(new pc.Vec3(.6, .7, 0)), height: 3.4 };
    cameraTarget.copy(cinematic.target);
    await fadeIn();
    await play(.9, () => {});
    await play(.6, t => {
      lying = 1 - t * t * (3 - 2 * t);
      cameraWobble.set(t < .5 && !reducedMotion.matches ? Math.sin(t * 120) * .08 : 0, 0, 0);
    });
    lying = undefined; cameraWobble.set(0, 0, 0);
    const aitor = npcs.find(n => n.entity.name === 'aitor');
    if (aitor) facing = visualFacing = facingToward(aitor.cell.x - movement.position.x, aitor.cell.z - movement.position.z);
    await play(.4, () => {});
    cutscene = false; cinematic = undefined; lastPrompt = ''; updatePrompt();
  }
  function startPalaceFight() {
    if (battle || environment.id !== 'palacio') return;
    clearInput();
    movement.teleport(environment.grid, movement.cell);
    encounterId = 'palace-minion';
    callbacks.onEncounter(2, 1, { possessed: false, encounter: 'palace-minion' });
  }
  /** The minion's head rises out of the manhole and pops a bubble: the dogs' eyes turn pink and they face the boys. */
  async function summonMinion() {
    if (environment.id !== 'maresme') { possessed = true; battleScene.possess(true); return; }
    cutscene = true; clearInput(); movement.walking = false; callbacks.onInteraction(undefined);
    await minion.emerge(() => {
      possessed = true; battleScene.possess(true);
      for (const dog of pack.dogs) {
        const p = pack.position(dog), at = scenery.toWorld(p.x, p.z);
        effects.emit('spore', new pc.Vec3(at.x, .9, at.z), 8, .3);
        dog.yaw = Math.atan2(movement.position.x - p.x, movement.position.z - p.z) * 180 / Math.PI;
        dog.wait = 4;
      }
    });
    cutscene = false; lastPrompt = ''; updatePrompt();
  }
  function setBattle(next: BattleState | undefined, effect?: BattleEffect, onImpact?: () => void) {
    if (!next && battle) {
      if (battle.encounter === 'dogs') pack.finish(battle.phase === 'won');
      callbacks.onBattleEnd(battle.phase, battle.encounter);
    }
    const stage = next?.encounter === 'palace-minion' || (!next && encounterId === 'palace-minion') ? PALACE_STAGE : pack.area.stage;
    const settled = battleScene.set(next, scenery.toWorld(stage.x, stage.z), effect, onImpact); battle = next; clearInput();
    if (!next) {
      movement.resolveOverlap(occupiedCells(), !reducedMotion.matches);
      lastPrompt = ''; positionPlayer(); updatePrompt();
    }
    else callbacks.onInteraction(undefined);
    return settled;
  }
  function touchDog(event: PointerEvent) {
    if (stopped() || battle || environment.id !== 'maresme') return;
    const rect = canvas.getBoundingClientRect();
    for (const dog of pack.dogs) {
      const position = pack.position(dog);
      const point = scenery.toWorld(position.x, position.z); point.y = .6;
      camera.camera!.worldToScreen(point, screen);
      if (Math.hypot(event.clientX - rect.left - screen.x, event.clientY - rect.top - screen.y) < 30) { encounter(); break; }
    }
  }
  canvas.addEventListener('pointerup', touchDog);

  const keyMap: Record<string, Direction> = {
    KeyW: 'up', KeyD: 'right', KeyS: 'down', KeyA: 'left',
    ArrowUp: 'up', ArrowRight: 'right', ArrowDown: 'down', ArrowLeft: 'left',
  };
  const held = new Map<string, Direction>();
  let controllerDirection: Direction | null = null;
  let controllerStick: Stick | null = null;
  let controllerRunning = false;
  let shiftHeld = false;
  /** Running needs the birthday shoes: Shift on the keyboard, held B on a controller. */
  const running = () => story.canRun && (controllerRunning || shiftHeld);
  let facing = 0;
  let visualFacing = 0;
  const walk = new WalkAnimation();
  let clock = 0;
  let lastStride = 0;
  let overview = false;
  let lastPrompt = '';
  // Walk-on stairs wait until Gerard lets go or walks away, so arriving never bounces him back.
  let stairsArmed = false;
  let arrival: Cell = { ...movement.cell };
  const cameraTarget = scenery.toWorld(movement.cell.x, movement.cell.z);
  const screen = new pc.Vec3();
  function clearInput() { held.clear(); shiftHeld = false; }
  function updatePrompt() {
    if (battle) return;
    const interaction = movement.bouncing ? undefined : nearby(movement.cell);
    const id = interaction?.id ?? '';
    if (id !== lastPrompt) { lastPrompt = id; callbacks.onInteraction(interaction); }
  }
  function positionPlayer() {
    const p = scenery.toWorld(movement.position.x, movement.position.z);
    const hop = movement.bouncing && !reducedMotion.matches ? Math.sin(movement.progress * Math.PI) * .18 : 0;
    player.setPosition(p.x, 0.09 + hop, p.z);
  }
  function setEnvironment(id: EnvironmentId, destination?: Cell) {
    if (battle) return;
    clearInput();
    scenery.destroy();
    environment = ENVIRONMENTS[id];
    scenery = buildScenery(app, environment);
    movement.teleport(environment.grid, destination ?? environment.spawn);
    stairsArmed = false; arrival = movement.cell;
    approach?.destroy(); approach = undefined;
    palace.root.enabled = false;
    if (id !== 'palacio') drainRisen = false;
    room = undefined;
    if (id === 'maresme') placePalace();
    refreshStory();
    // A new scene opens in its final light; only the story's turn fades.
    tone = toneTarget; scenery.setTone(tone);
    if (bernatHere()) follower.reset(beside(movement.cell));
    overview = false;
    lastPrompt = '';
    callbacks.onInteraction(undefined);
    callbacks.onLocation(id, movement.cell);
    cameraTarget.copy(scenery.toWorld(movement.cell.x, movement.cell.z));
    positionPlayer(); updatePrompt();
  }
  function interact() {
    if (stopped() || battle || movement.bouncing) return;
    if (story.battles && environment.id === 'maresme' && pack.touching(movement.position, 1.5)) { encounter(); return; }
    const target = nearby(movement.position);
    if (!target) return;
    clearInput();
    // The story may hold a door shut; doors and stairs travel; lines are Gerard's own comments.
    const gate = story.gate(target.id);
    if (gate) callbacks.onDialogue(gate);
    else if (target.to) setEnvironment(target.to.environment, target.to.cell);
    else if (target.lines) callbacks.onDialogue({ left: 'gerard', lines: target.lines.map(text => ({ speaker: 'gerard' as const, text })) });
    else callbacks.onStory({ type: 'interact', id: target.id });
  }
  function keydown(event: KeyboardEvent) {
    if (stopped() || battle || document.querySelector('#hud[data-dialogue]')) return;
    if (event.target instanceof HTMLElement && event.target.closest('select, input, textarea, button')) return;
    if (event.altKey || event.ctrlKey || event.metaKey) return;
    if (event.code === 'KeyE' || event.code === 'Space' || event.code === 'Enter') {
      event.preventDefault(); if (!event.repeat) interact(); return;
    }
    if (event.code === 'KeyR') { if (!event.repeat) overview = !overview; return; }
    if (event.code === 'ShiftLeft' || event.code === 'ShiftRight') { shiftHeld = true; return; }
    const direction = keyMap[event.code];
    if (!direction) return;
    event.preventDefault();
    held.set(event.code, direction);
  }
  function keyup(event: KeyboardEvent) {
    held.delete(event.code);
    if (event.code === 'ShiftLeft' || event.code === 'ShiftRight') shiftHeld = false;
  }
  function resize() { app.resizeCanvas(); }
  window.addEventListener('keydown', keydown);
  window.addEventListener('keyup', keyup);
  window.addEventListener('blur', clearInput);
  document.addEventListener('visibilitychange', clearInput);
  window.addEventListener('resize', resize);
  resize(); positionPlayer();
  camera.setPosition(cameraTarget.x + 40, cameraTarget.y + 52, cameraTarget.z + 40);
  callbacks.onLocation(environment.id, movement.cell);
  app.on('update', (dt: number) => {
    const delta = Math.min(dt, 0.05);
    if (!stopped() && !battle && !document.querySelector('#hud[data-dialogue]')) {
      movement.update(dt);
      // Everything steers in screen space: held keys add up, otherwise the stick or D-pad.
      const keys = [...new Set(held.values())].reduce((sum, d) => ({ x: sum.x + SCREEN_VECTORS[d].x, y: sum.y + SCREEN_VECTORS[d].y }), { x: 0, y: 0 });
      const keyLength = Math.hypot(keys.x, keys.y);
      let input: Stick | null = keyLength ? { x: keys.x / keyLength, y: keys.y / keyLength } : null;
      if (!input && controllerStick) {
        // Analog tilt walks slower, but never so slow that it looks stuck.
        const length = Math.hypot(controllerStick.x, controllerStick.y);
        const tilt = Math.min(1, Math.max(0.35, (length - 0.2) / 0.7));
        input = { x: controllerStick.x / length * tilt, y: controllerStick.y / length * tilt };
      }
      if (!input && controllerDirection) input = SCREEN_VECTORS[controllerDirection];
      if (input) {
        const grid = screenToGrid(input.x, input.y);
        facing = facingToward(grid.x, grid.z);
        if (movement.drive(grid.x, grid.z, dt, occupiedCells(), running())) callbacks.onStep(movement.steps, movement.cell);
        if (movement.walking) overview = false;
      } else movement.walking = false;
      const here = movement.cell;
      if (!input || Math.hypot(here.x - arrival.x, here.z - arrival.z) > 2.5) stairsArmed = true;
      const stairs = environment.interactions.find(({ step: r }) => r && here.x >= r.x && here.x < r.x + r.w && here.z >= r.z && here.z < r.z + r.d);
      if (stairs?.to && stairsArmed && input) {
        const gate = story.gate(stairs.id);
        if (gate) { clearInput(); callbacks.onDialogue(gate); } else setEnvironment(stairs.to.environment, stairs.to.cell);
      }
      if (bernatHere()) {
        follower.update(delta, movement.position, story.companion === 'stalled', running());
        // Walking on past the south row with Bernat makes him stall; pulling at the leash escalates.
        if (environment.id === 'maresme' && story.companion === 'follow' && !story.has('bernat-stalled') && movement.position.z >= PLACES.southRow) callbacks.onStory({ type: 'south' });
        const far = Math.hypot(movement.position.x - follower.position.x, movement.position.z - follower.position.z) > LEASH - 0.6;
        tug = story.companion === 'stalled' && input && far ? tug + Math.min(dt, .25) : 0;
        if (tug > 0.9) { tug = 0; callbacks.onStory({ type: 'leash' }); }
      }
      // Rooms tell the story when Gerard steps into them (the wrapper room's minion).
      if (environment.palace) {
        const c = movement.cell;
        const here = environment.palace.rooms.find(r => c.x >= r.x && c.x < r.x + r.w && c.z >= r.z && c.z < r.z + r.d)?.name;
        if (here !== room) { room = here; if (here) callbacks.onStory({ type: 'room', id: here }); }
      }
      // Heading back south once the palace stands: Bernat says it is the other way.
      if (environment.id === 'maresme' && story.palace && !story.has('in-palace')) {
        const south = movement.position.z > PLACES.awayRow;
        if (south !== away) { away = south; callbacks.onStory({ type: 'away', away }); }
      }
      positionPlayer(); updatePrompt();
      if (environment.id === 'maresme' && !battle) {
        pack.update(delta, movement.footprint);
        if (!movement.bouncing && pack.armed && pack.touching(movement.position)) encounter();
      }
    } else { clearInput(); movement.walking = false; }
    const walking = movement.walking && !paused && !battle && !document.querySelector('#hud[data-dialogue]');
    const animate = !reducedMotion.matches;
    const pose = walk.update(delta * (running() && walking ? 2 : 1), !!walking, animate);
    clock += delta;
    // Each footfall kicks up a small puff under the planted shoe.
    if (walking && animate && Math.sign(pose.stride) !== Math.sign(lastStride) && Math.abs(pose.stride) > 1) {
      const foot = rig.feet[pose.stride > 0 ? 1 : 0].getPosition();
      effects.emit('dust', new pc.Vec3(foot.x, scenery.groundHeight(foot.x, foot.z) + .05, foot.z), 2, .08);
    }
    lastStride = pose.stride;
    const idle = idlePose(clock);
    const resting = animate && !walking && !battle ? 1 - pose.weight : 0;
    const turn = ((facing - visualFacing + 540) % 360) - 180;
    visualFacing += turn * (reducedMotion.matches ? 1 : 1 - Math.exp(-delta / .065));
    visualFacing = ((visualFacing + 180) % 360 + 360) % 360 - 180;
    rig.body.setLocalEulerAngles(0, visualFacing, pose.sway);
    rig.limbs.forEach((limb, i) => limb.setLocalEulerAngles(pose.stride * (i === 0 || i === 3 ? 1 : -1) * (i % 2 ? .8 : 1), 0, 0));
    rig.body.setLocalPosition(0, 0, 0);
    rig.body.setLocalScale(1, 1 + idle.breathe * .016 * resting, 1);
    rig.head.setLocalEulerAngles(-idle.breathe * 2 * resting, idle.look * 16 * resting, 0);
    rig.eyes.forEach((eye, i) => { const s = eye.getLocalScale(); eye.setLocalScale(s.x, rig.eyeHeights[i] * (animate ? idle.blink : 1), s.z); });
    const separationHop = movement.bouncing && !reducedMotion.matches ? Math.sin(movement.progress * Math.PI) * .18 : 0;
    plantFeet(scenery.groundHeight, separationHop);
    if (lying !== undefined) {
      // On his back on the mattress, head on the pillows against the west wall; sitting up swings him onto his feet.
      const k = lying, rest = scenery.toWorld(PLACES.bed.x, PLACES.bed.z), stand = player.getPosition();
      const hop = Math.sin((1 - k) * Math.PI) * .25;
      player.setPosition(pc.math.lerp(stand.x, rest.x, k), pc.math.lerp(stand.y, .93, k) + hop, pc.math.lerp(stand.z, rest.z, k));
      player.setLocalEulerAngles(0, 0, 90 * k);
      facing = visualFacing = 90;
      rig.body.setLocalEulerAngles(0, 90, 0);
    } else if (player.getLocalEulerAngles().z !== 0) player.setLocalEulerAngles(0, 0, 0);
    // Story cast: Bernat walks his own gait; people at home turn to face Gerard when he is near.
    companion.enabled = companionShown && !battle;
    if (companion.enabled) {
      const bernatPose = bernatWalk.update(delta * (running() && follower.walking ? 2 : 1), follower.walking && !paused, animate);
      const p = scenery.toWorld(follower.position.x, follower.position.z);
      companion.setPosition(p.x, 0.09, p.z);
      const facingGerard = !follower.walking && story.companion !== 'stalled';
      const yaw = facingGerard ? facingToward(movement.position.x - follower.position.x, movement.position.z - follower.position.z) : follower.facing;
      bernatRig.body.setLocalEulerAngles(0, yaw, bernatPose.sway);
      bernatRig.limbs.forEach((limb, i) => limb.setLocalEulerAngles(bernatPose.stride * (i === 0 || i === 3 ? 1 : -1) * (i % 2 ? .8 : 1), 0, 0));
      plantBernat(scenery.groundHeight, 0);
    }
    for (const npc of npcs) {
      const dx = movement.position.x - npc.cell.x, dz = movement.position.z - npc.cell.z;
      if (Math.hypot(dx, dz) < 4) npc.body.setLocalEulerAngles(0, facingToward(dx, dz), 0);
    }
    pickups.forEach((p, i) => {
      // Things lying on furniture stay put (the wrapper on the bedside shelf); loose ones float.
      if (p.spot) { const at = scenery.toWorld(p.spot.x, p.spot.z); p.entity.setPosition(at.x, p.spot.y, at.z); p.entity.setLocalEulerAngles(0, 25, 0); return; }
      if (animate) p.entity.setLocalEulerAngles(0, clock * 60 + i * 90, 0);
      placeOnGround(p.entity, p.cell, .75 + (animate ? Math.sin(clock * 2.4 + i) * .06 : 0));
    });
    spores = Math.max(0, spores - delta);
    battleScene.dogs.forEach((model, i) => {
      const dog = pack.dogs[i];
      model.enabled = environment.id === 'maresme' && !battle && !!dog;
      if (!dog) return;
      // Possessed dogs give off pink motes, so their state reads from the street camera.
      if (possessed && animate && spores === 0 && i === sporeDog % pack.dogs.length) {
        effects.emit('spore', model.getPosition().clone().add(new pc.Vec3(0, .9, 0)), 1, .15);
        spores = .3; sporeDog++;
      }
      const p = pack.position(dog);
      model.setPosition(scenery.toWorld(p.x, p.z));
      model.setEulerAngles(0, dog.yaw, 0);
      battleScene.wander(i, delta, dog.progress < 1 && !paused && !battle && !document.querySelector('#hud[data-dialogue]'), !reducedMotion.matches);
    });
    if (timeline) {
      timeline.elapsed += reducedMotion.matches ? timeline.seconds : delta;
      const t = Math.min(1, timeline.elapsed / timeline.seconds);
      timeline.step(t);
      if (t >= 1) { const { done } = timeline; timeline = undefined; done(); }
    }
    palace.update(delta, animate);
    // The minion lives under the street's manhole, and in the palace under the wrapper room's drain.
    const lair = environment.id === 'palacio' ? PLACES.drain : PLACES.minion.manhole;
    minion.update(delta, animate, {
      manhole: scenery.toWorld(lair.x, lair.z), look: player.getPosition(), groundHeight: scenery.groundHeight,
    }, (environment.id === 'maresme' || environment.id === 'palacio') && !battle);
    if (tone !== toneTarget) {
      tone = animate ? tone + Math.sign(toneTarget - tone) * Math.min(Math.abs(toneTarget - tone), delta / 3.5) : toneTarget;
      scenery.setTone(tone);
    }
    camera.camera!.clearColor = clear.lerp(dayClear, BUBBALOO.clear, tone);
    battleScene.update(delta, animate);
    scenery.update(delta, animate, new pc.Vec3(0, .7, 0).add(player.getPosition()), camera.forward.clone().mulScalar(-1));
    effects.update(delta);
    const aspect = canvas.clientWidth / canvas.clientHeight;
    const follow = environment.zoom;
    const target = battle ? battleScene.anchor.clone().add(new pc.Vec3(0, 1, 0)).add(battleScene.focus) : cinematic ? cinematic.target.clone() : follow && !overview ? player.getPosition().clone() : new pc.Vec3();
    cameraTarget.lerp(cameraTarget, target, reducedMotion.matches ? 1 : 1 - Math.exp(-delta * 7));
    const cameraOffset = battle ? new pc.Vec3(5, 9, 15) : new pc.Vec3(40, 52, 40);
    if (battleScene.entering && !reducedMotion.matches) {
      const arc = Math.sin(battleScene.entryProgress * Math.PI);
      cameraOffset.add(new pc.Vec3(arc * 3, arc * 1.5, -arc * 2));
    }
    const desiredCamera = cameraTarget.clone().add(cameraOffset);
    camera.setPosition(reducedMotion.matches ? desiredCamera : camera.getPosition().clone().lerp(camera.getPosition(), desiredCamera, 1 - Math.exp(-delta * 6)));
    if (battle) camera.setPosition(camera.getPosition().clone().add(battleScene.cameraKick));
    else if (cinematic) camera.setPosition(camera.getPosition().clone().add(cameraWobble));
    camera.lookAt(cameraTarget);
    const halfWidth = (environment.grid[0].length + environment.grid.length) * Math.SQRT1_2 / 2 + 2;
    const fullHeight = (environment.grid[0].length + environment.grid.length) / Math.sqrt(6) / 2 + 4;
    const height = battle ? Math.max(5.7, 4.8 / aspect, battle.foes.length * 1.1 + 2) : cinematic ? Math.max(cinematic.height, cinematic.height * 1.3 / aspect) : follow && !overview ? Math.max(follow, follow * 6 / 7 / aspect) : Math.max(fullHeight, halfWidth / aspect);
    camera.camera!.orthoHeight = pc.math.lerp(camera.camera!.orthoHeight, height, reducedMotion.matches ? 1 : 1 - Math.exp(-delta * 6));
    callbacks.onBattleTargets(battleScene.targets().map(({ id, position, visible }) => {
      camera.camera!.worldToScreen(position, screen);
      return { id, x: screen.x, y: screen.y, visible };
    }));
    if (companion.enabled) {
      camera.camera!.worldToScreen(companion.getPosition().clone().add(new pc.Vec3(0, 1.75, 0)), screen);
      callbacks.onCompanionScreen({ x: screen.x, y: screen.y });
    } else callbacks.onCompanionScreen(undefined);

  });
  app.on('destroy', () => {
    window.removeEventListener('keydown', keydown); window.removeEventListener('keyup', keyup);
    window.removeEventListener('blur', clearInput); document.removeEventListener('visibilitychange', clearInput);
    window.removeEventListener('resize', resize);
    canvas.removeEventListener('pointerup', touchDog);
    battleScene.destroy(); minion.destroy(); palace.destroy(); approach?.destroy(); effects.destroy();
    scenery.destroy(); rig.materials.forEach(m => m.destroy()); bernatRig.materials.forEach(m => m.destroy());
    for (const list of [npcs, pickups]) for (const item of list) item.materials.forEach(m => m.destroy());
  });
  refreshStory();
  tone = toneTarget; scenery.setTone(tone);
  app.start();
  return {
    app, setEnvironment, interact, encounter, setBattle, refreshStory, summonMinion,
    raisePalace, popGate, riseFromDrain, startPalaceFight, ambush, wake,
    /** Gerard's class woke up mid-fight: the fight shows it now, the street model wears it after. */
    awaken(id: ClassId) { battleScene.awaken(id); wearClass(player, id); },
    setControllerInput(direction: Direction | null, stick: Stick | null, running = false) { controllerDirection = direction; controllerStick = stick; controllerRunning = running; },
    selectTarget: battleScene.selectTarget,
    setPaused(value: boolean) { paused = value; clearInput(); controllerDirection = null; controllerStick = null; controllerRunning = false; },
    get position() { return movement.position; },
    get companionPosition() { return follower.position; },
    /** Whether Gerard is moving fast enough to count as running; the run hint waits for it. */
    get running() { return running() && movement.walking; },
    toggleOverview() { if (stopped() || battle) return; overview = !overview; canvas.focus({ preventScroll: true }); },
    press(direction: Direction) { if (paused || battle) return; held.set('touch', direction); },
    release() { held.delete('touch'); },
  };
}
